var LANG_ORDER = ['tr','en','ru','de','fr','it','ar'];
var currentLang = localStorage.getItem('sb_lang') || 'tr';

function applyLang(code) {
  var t = LANGS[code];
  if (!t) return;
  currentLang = code;
  localStorage.setItem('sb_lang', code);

  // RTL
  document.documentElement.dir = t.dir;
  document.documentElement.lang = code;

  // Apply translations
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Update lang picker active state
  document.querySelectorAll('.lang-opt').forEach(function(opt) {
    opt.classList.toggle('active', opt.dataset.lang === code);
  });

  // Update current label
  var lbl = document.getElementById('langCurrent');
  if (lbl) lbl.textContent = t.flag;
}

window.toggleLangMenu = function() {
  var m = document.getElementById('langMenu');
  if (m) m.classList.toggle('open');
};
window.selectLang = function(code) {
  applyLang(code);
  var m = document.getElementById('langMenu');
  if (m) m.classList.remove('open');
};

// Close on outside click
document.addEventListener('click', function(e) {
  var picker = document.getElementById('langPicker');
  if (picker && !picker.contains(e.target)) {
    var m = document.getElementById('langMenu');
    if (m) m.classList.remove('open');
  }
});

// Init
document.addEventListener('DOMContentLoaded', function() {
  applyLang(currentLang);
});

// Expose
window.StudioI18n = { apply: applyLang, langs: LANGS };

